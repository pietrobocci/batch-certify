// Deploys BatchCertificate and prepares everything the frontend needs.
//
// Prerequisite: a node listening on 127.0.0.1:8545 (npm run node).
// Usage:        npm run deploy
//
// What it does:
//   1. deploys the contract, with the deployer as role admin
//   2. grants ISSUER_ROLE to the deployer (fine for local development;
//      on a public network roles would go to distinct accounts)
//   3. writes deployed.json (address + network) and exports the ABI
//      to frontend/src/contract-abi.json so the UI always talks to
//      the freshly deployed contract.
const fs = require("fs");
const path = require("path");
const { ethers, network, artifacts } = require("hardhat");
const { waitForNode } = require("./helpers/wait-for-node");

async function main() {
  await waitForNode(ethers.provider);

  const [deployer] = await ethers.getSigners();
  console.log(`Network:  ${network.name}`);
  console.log(`Deployer: ${deployer.address}`);

  // The deployer becomes the role admin (constructor argument)...
  const contract = await ethers.deployContract("BatchCertificate", [deployer.address]);
  await contract.waitForDeployment();
  console.log(`BatchCertificate deployed at ${contract.target}`);

  // ...and, for local development only, also an issuer.
  const tx = await contract.grantRole(await contract.ISSUER_ROLE(), deployer.address);
  await tx.wait();
  console.log(`ISSUER_ROLE granted to deployer`);

  // Hand the frontend what it needs: address + ABI.
  const root = path.join(__dirname, "..");
  fs.writeFileSync(
    path.join(root, "deployed.json"),
    JSON.stringify(
      { network: network.name, address: contract.target, deployedAt: new Date().toISOString() },
      null,
      2
    )
  );

  // Exported as a .ts file with `as const` so wagmi/viem can infer the
  // exact function names and argument types from the ABI: typos in
  // functionName or wrong argument types become compile-time errors.
  const artifact = await artifacts.readArtifact("BatchCertificate");
  const frontendDir = path.join(root, "frontend", "src", "generated");
  if (fs.existsSync(path.join(root, "frontend"))) {
    fs.mkdirSync(frontendDir, { recursive: true });
    fs.writeFileSync(
      path.join(frontendDir, "contract.ts"),
      "// AUTO-GENERATED by scripts/deploy.js — do not edit by hand.\n" +
        `export const contractAddress = ${JSON.stringify(contract.target)} as const;\n\n` +
        `export const contractAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`
    );
    console.log(`ABI + address exported to frontend/src/generated/contract.ts`);
  }

  console.log("\nDone. Start the UI with: cd frontend && npm run dev");
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
