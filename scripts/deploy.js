// Deploys BatchCertificate and prepares everything the frontend needs.
//
// Local:    npm run deploy            (node must be running: npm run node)
// Sepolia:  npm run deploy:sepolia    (needs .env, see .env.example)
//
// Multichain bookkeeping: deployed.json maps chainId -> deployment, so a
// local deploy and a Sepolia deploy coexist. The generated
// frontend/src/generated/contract.ts exports that same map; the UI picks
// the right address from the chain the wallet is on (useChainId).
const fs = require("fs");
const path = require("path");
const { ethers, network, artifacts } = require("hardhat");
const { waitForNode } = require("./helpers/wait-for-node");

async function main() {
  await waitForNode(ethers.provider);

  const [deployer] = await ethers.getSigners();
  const chainId = Number((await ethers.provider.getNetwork()).chainId);
  console.log(`Network:  ${network.name} (chainId ${chainId})`);
  console.log(`Deployer: ${deployer.address}`);

  const contract = await ethers.deployContract("BatchCertificate", [deployer.address]);
  await contract.waitForDeployment();
  console.log(`BatchCertificate deployed at ${contract.target}`);

  // Locally the deployer doubles as issuer for convenience. On a public
  // network the same works for a demo, but roles could go to separate
  // accounts (admin hardware wallet, issuer hot wallet).
  const tx = await contract.grantRole(await contract.ISSUER_ROLE(), deployer.address);
  await tx.wait();
  console.log(`ISSUER_ROLE granted to deployer`);

  // --- update the per-chain deployment map ---
  const root = path.join(__dirname, "..");
  const deployedFile = path.join(root, "deployed.json");
  const deployments = fs.existsSync(deployedFile)
    ? JSON.parse(fs.readFileSync(deployedFile, "utf8"))
    : {};
  deployments[chainId] = {
    network: network.name,
    address: contract.target,
    deployedAt: new Date().toISOString(),
  };
  fs.writeFileSync(deployedFile, JSON.stringify(deployments, null, 2));

  // --- regenerate the typed frontend module (address map + as-const ABI) ---
  const artifact = await artifacts.readArtifact("BatchCertificate");
  const frontendDir = path.join(root, "frontend", "src", "generated");
  if (fs.existsSync(path.join(root, "frontend"))) {
    fs.mkdirSync(frontendDir, { recursive: true });
    const addresses = Object.fromEntries(
      Object.entries(deployments).map(([id, d]) => [id, d.address])
    );
    fs.writeFileSync(
      path.join(frontendDir, "contract.ts"),
      "// AUTO-GENERATED by scripts/deploy.js — do not edit by hand.\n" +
        "export const contractAddresses: Record<number, `0x${string}`> =\n" +
        `  ${JSON.stringify(addresses, null, 2)};\n\n` +
        `export const contractAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`
    );
    console.log(`Address map + ABI exported to frontend/src/generated/contract.ts`);
  }

  console.log("\nDone.");
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
